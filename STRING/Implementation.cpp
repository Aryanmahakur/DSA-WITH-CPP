// ========================= C++ STRING STL REVISION SHEET =========================

#include <iostream>
#include <string>
#include <algorithm>
#include <cctype>
using namespace std;

int main() {

    //--------------------------------------------------------------------------
    // 1. Create String
    //--------------------------------------------------------------------------

    string s = "Hello";
    cout << "Create : " << s << endl;                         // Hello

    //--------------------------------------------------------------------------
    // 2. size() / length()
    //--------------------------------------------------------------------------

    cout << "Size : " << s.size() << endl;                    // 5
    cout << "Length : " << s.length() << endl;                // 5

    //--------------------------------------------------------------------------
    // 3. Access Character
    //--------------------------------------------------------------------------

    cout << "s[1] : " << s[1] << endl;                        // e
    cout << "at(1) : " << s.at(1) << endl;                    // e

    //--------------------------------------------------------------------------
    // 4. front() / back()
    //--------------------------------------------------------------------------

    cout << "Front : " << s.front() << endl;                  // H
    cout << "Back : " << s.back() << endl;                    // o

    //--------------------------------------------------------------------------
    // 5. push_back()
    //--------------------------------------------------------------------------

    string a = "Hello";
    a.push_back('!');
    cout << "push_back : " << a << endl;                      // Hello!

    //--------------------------------------------------------------------------
    // 6. pop_back()
    //--------------------------------------------------------------------------

    a.pop_back();
    cout << "pop_back : " << a << endl;                       // Hello

    //--------------------------------------------------------------------------
    // 7. append()
    //--------------------------------------------------------------------------

    string b = "Hello";
    b.append(" World");
    cout << "append : " << b << endl;                         // Hello World

    //--------------------------------------------------------------------------
    // 8. Concatenate (+)
    //--------------------------------------------------------------------------

    string s1 = "Hello";
    string s2 = " World";
    cout << "Concatenate : " << s1 + s2 << endl;              // Hello World

    //--------------------------------------------------------------------------
    // 9. insert()
    //--------------------------------------------------------------------------

    string c = "Hello";
    c.insert(2,"ABC");
    cout << "insert : " << c << endl;                         // HeABCllo

    //--------------------------------------------------------------------------
    // 10. erase()
    //--------------------------------------------------------------------------

    string d = "Hello";
    d.erase(1,2);
    cout << "erase : " << d << endl;                          // Hlo

    //--------------------------------------------------------------------------
    // 11. replace()
    //--------------------------------------------------------------------------

    string e = "Hello";
    e.replace(1,2,"AB");
    cout << "replace : " << e << endl;                        // HABlo

    //--------------------------------------------------------------------------
    // 12. substr()
    //--------------------------------------------------------------------------

    string f = "Programming";
    cout << "substr : " << f.substr(3,5) << endl;             // gramm

    //--------------------------------------------------------------------------
    // 13. find()
    //--------------------------------------------------------------------------

    cout << "find : " << f.find("gram") << endl;              // 3

    if(f.find("xyz")==string::npos)
        cout << "find : Not Found" << endl;

    //--------------------------------------------------------------------------
    // 14. reverse()
    //--------------------------------------------------------------------------

    string g = "Hello";
    reverse(g.begin(),g.end());
    cout << "reverse : " << g << endl;                        // olleH

    //--------------------------------------------------------------------------
    // 15. sort()
    //--------------------------------------------------------------------------

    string h = "dbca";
    sort(h.begin(),h.end());
    cout << "sort : " << h << endl;                           // abcd

    //--------------------------------------------------------------------------
    // 16. compare()
    //--------------------------------------------------------------------------

    string x="abc";
    string y="abc";
    cout << "compare : " << x.compare(y) << endl;             // 0

    string p="abc";
    string q="abd";
    cout << "compare : " << p.compare(q) << endl;             // -1

    //--------------------------------------------------------------------------
    // 17. ==
    //--------------------------------------------------------------------------

    cout << "== : " << (x==y) << endl;                        // 1

    //--------------------------------------------------------------------------
    // 18. empty()
    //--------------------------------------------------------------------------

    string emp="";
    cout << "empty : " << emp.empty() << endl;                // 1

    //--------------------------------------------------------------------------
    // 19. clear()
    //--------------------------------------------------------------------------

    string clr="Hello";
    clr.clear();
    cout << "clear : " << clr.size() << endl;                 // 0

    //--------------------------------------------------------------------------
    // 20. resize()
    //--------------------------------------------------------------------------

    string rs="Hello";
    rs.resize(3);
    cout << "resize : " << rs << endl;                        // Hel

    //--------------------------------------------------------------------------
    // 21. swap()
    //--------------------------------------------------------------------------

    string u="Hello";
    string v="World";
    u.swap(v);
    cout << "swap : " << u << " " << v << endl;               // World Hello

    //--------------------------------------------------------------------------
    // 22. Iteration
    //--------------------------------------------------------------------------

    string it="Hello";
    cout << "Iteration : ";
    for(char c:it)
        cout<<c<<" ";
    cout<<endl;                                               // H e l l o

    //--------------------------------------------------------------------------
    // 23. getline()
    //--------------------------------------------------------------------------

    // string line;
    // getline(cin,line);
    // cout<<line;

    //--------------------------------------------------------------------------
    // 24. Character Functions (<cctype>)
    //--------------------------------------------------------------------------

    cout << "isalpha('A') : " << isalpha('A') << endl;        // 1
    cout << "isdigit('5') : " << isdigit('5') << endl;        // 1
    cout << "isalnum('A') : " << isalnum('A') << endl;        // 1
    cout << "islower('a') : " << islower('a') << endl;        // 1
    cout << "isupper('A') : " << isupper('A') << endl;        // 1
    cout << "isspace(' ') : " << isspace(' ') << endl;        // 1

    cout << "tolower('A') : " << (char)tolower('A') << endl;  // a
    cout << "toupper('a') : " << (char)toupper('a') << endl;  // A

    //--------------------------------------------------------------------------
    // 25. String → Number
    //--------------------------------------------------------------------------

    cout << "stoi : " << stoi("123") << endl;                 // 123
    cout << "stol : " << stol("123456") << endl;              // 123456
    cout << "stoll : " << stoll("1234567890123") << endl;     // 1234567890123
    cout << "stof : " << stof("12.5") << endl;                // 12.5
    cout << "stod : " << stod("15.789") << endl;              // 15.789

    //--------------------------------------------------------------------------
    // 26. Number → String
    //--------------------------------------------------------------------------

    int num=100;
    string str=to_string(num);
    cout << "to_string : " << str << endl;                    // 100

    //--------------------------------------------------------------------------
    // 27. Lexicographical Comparison
    //--------------------------------------------------------------------------

    cout << ("apple" < string("banana")) << endl;             // 1

    return 0;
}