// ========================= ARRAY REVISION SHEET =========================

#include <iostream>
#include <algorithm>
#include <numeric>
using namespace std;

int main() {

    //------------------------------------------------------------------
    // 1. Create Array
    //------------------------------------------------------------------

    int arr[5] = {10,20,30,40,50};

    //------------------------------------------------------------------
    // 2. Access Elements
    //------------------------------------------------------------------

    cout << arr[0] << endl;          // 10
    cout << arr[4] << endl;          // 50

    //------------------------------------------------------------------
    // 3. Update Element
    //------------------------------------------------------------------

    arr[2] = 100;
    cout << arr[2] << endl;          // 100

    //------------------------------------------------------------------
    // 4. Size of Array
    //------------------------------------------------------------------

    int n = sizeof(arr)/sizeof(arr[0]);
    cout << n << endl;               // 5

    //------------------------------------------------------------------
    // 5. Traverse Array
    //------------------------------------------------------------------

    for(int i=0;i<n;i++)
        cout << arr[i] << " ";

    cout << endl;
    // 10 20 100 40 50

    //------------------------------------------------------------------
    // 6. Range-Based Loop
    //------------------------------------------------------------------

    for(int x : arr)
        cout << x << " ";

    cout << endl;
    // 10 20 100 40 50

    //------------------------------------------------------------------
    // 7. Sort Ascending
    //------------------------------------------------------------------

    int a[]={5,2,4,1,3};

    sort(a,a+5);

    for(int x:a)
        cout<<x<<" ";

    cout<<endl;
    // 1 2 3 4 5

    //------------------------------------------------------------------
    // 8. Sort Descending
    //------------------------------------------------------------------

    sort(a,a+5,greater<int>());

    for(int x:a)
        cout<<x<<" ";

    cout<<endl;
    // 5 4 3 2 1

    //------------------------------------------------------------------
    // 9. Reverse
    //------------------------------------------------------------------

    reverse(a,a+5);

    for(int x:a)
        cout<<x<<" ";

    cout<<endl;

    //------------------------------------------------------------------
    // 10. Find Element
    //------------------------------------------------------------------

    int b[]={10,20,30,40};

    auto it=find(b,b+4,30);

    if(it!=b+4)
        cout<<"Found"<<endl;
    else
        cout<<"Not Found"<<endl;

    // Found

    //------------------------------------------------------------------
    // 11. Binary Search
    //------------------------------------------------------------------

    int c[]={1,2,3,4,5};

    cout<<binary_search(c,c+5,4)<<endl;

    // 1

    //------------------------------------------------------------------
    // 12. Maximum Element
    //------------------------------------------------------------------

    int d[]={4,7,1,9,5};

    cout<<*max_element(d,d+5)<<endl;

    // 9

    //------------------------------------------------------------------
    // 13. Minimum Element
    //------------------------------------------------------------------

    cout<<*min_element(d,d+5)<<endl;

    // 1

    //------------------------------------------------------------------
    // 14. Sum of Elements
    //------------------------------------------------------------------

    cout<<accumulate(d,d+5,0)<<endl;

    // 26

    //------------------------------------------------------------------
    // 15. Count Occurrence
    //------------------------------------------------------------------

    int e[]={1,2,2,3,2};

    cout<<count(e,e+5,2)<<endl;

    // 3

    //------------------------------------------------------------------
    // 16. Fill Array
    //------------------------------------------------------------------

    int f[5];

    fill(f,f+5,10);

    for(int x:f)
        cout<<x<<" ";

    cout<<endl;

    // 10 10 10 10 10

    //------------------------------------------------------------------
    // 17. Copy Array
    //------------------------------------------------------------------

    int g[]={1,2,3,4,5};

    int h[5];

    copy(g,g+5,h);

    for(int x:h)
        cout<<x<<" ";

    cout<<endl;

    // 1 2 3 4 5

    //------------------------------------------------------------------
    // 18. Swap Arrays
    //------------------------------------------------------------------

    int x[]={1,2,3};
    int y[]={4,5,6};

    swap(x,y);

    for(int i:x)
        cout<<i<<" ";

    cout<<endl;

    // 4 5 6

    //------------------------------------------------------------------
    // 19. Input
    //------------------------------------------------------------------

    int arr2[5];

    // for(int i=0;i<5;i++)
    //     cin>>arr2[i];

    //------------------------------------------------------------------
    // 20. Output
    //------------------------------------------------------------------

    // for(int i=0;i<5;i++)
    //     cout<<arr2[i]<<" ";

    return 0;
}